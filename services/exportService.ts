const toRenpyId = (str: string) => str.replace(/[^a-zA-Z0-9_]/g, '_').toLowerCase();

/**
 * 웹 패키지(.zip)를 위한 경로 치환된 시나리오 데이터를 생성합니다.
 */
export function prepareWebPackageData(vn: VisualNovel) {
    return prepareWebPackageAssets(vn).data;
}

export function exportToRenpy(vn: VisualNovel): string {
  const plan = prepareRenpyExportData(vn);
  const script: string[] = ["# Ren'Py script generated by VN-AI Studio", '# -*- coding: utf-8 -*-',
    "# Put this file and the 'images' folder into your Ren'Py project's game directory.",
    '# Plain text only; generated aliases are recorded in id-map.json.', ''];
  const characterPlan = new Map(plan.characters.map(character => [character.id, character]));
  const scenePlan = new Map(plan.scenes.map(scene => [scene.id, scene]));
  for (const character of plan.characters) for (const expression of character.expressions) {
    if (expression.path) script.push(`image ${character.imageTag} ${expression.attribute} = ${JSON.stringify(expression.path)}`);
  }
  for (const scene of plan.scenes) if (scene.path) script.push(`image ${scene.imageTag} = ${JSON.stringify(scene.path)}`);
  script.push('');
  for (const character of vn.characters) script.push(`define ${characterPlan.get(character.id)!.variable} = Character(${quoteRenpyText(character.name)})`);
  script.push('', 'label start:', `    jump ${scenePlan.get(vn.startSceneId)!.label}`, '');
  const positions = ['left', 'right', 'center', 'truecenter'];
  function show(characterId: string, expressionId: string | null, position?: string) {
    const character = vn.characters.find(item => item.id === characterId)!;
    const mapped = characterPlan.get(characterId)!;
    const expression = (expressionId && mapped.expressions.find(item => item.id === expressionId))
      || mapped.expressions.find(item => character.expressions.find(e => e.id === item.id)?.name === '중립') || mapped.expressions[0];
    if (expression?.path) script.push(`    show ${mapped.imageTag} ${expression.attribute}${position ? ' at ' + position : ''} with dissolve`);
    else script.push(`    hide ${mapped.imageTag}`);
  }
  for (const scene of vn.scenes) {
    const mapped = scenePlan.get(scene.id)!;
    script.push(`label ${mapped.label}:`, '', mapped.path ? `    scene ${mapped.imageTag} with fade` : '    scene');
    for (const character of plan.characters) script.push(`    hide ${character.imageTag}`);
    scene.presentCharacterIds.forEach((id, index) => show(id, null, positions[index % positions.length]));
    for (const line of scene.dialogue) {
      if (line.characterId !== null) {
        if (scene.presentCharacterIds.includes(line.characterId)) show(line.characterId, line.expressionId);
        script.push(`    ${characterPlan.get(line.characterId)!.variable} ${quoteRenpyText(line.text)}`);
      } else script.push(`    ${quoteRenpyText(line.text)}`);
    }
    if (scene.choices.length) {
      script.push('', '    menu:');
      for (const choice of scene.choices) script.push(`        ${quoteRenpyText(choice.text)}:`, `            jump ${scenePlan.get(choice.nextSceneId)!.label}`);
    } else script.push('', '    # Ending scene', '    return');
    script.push('');
  }
  return script.join('\n');
}

export function exportToHtml(vn: VisualNovel, isPackage: boolean = false, uiLanguage: ContentLanguage = resolveContentLanguage(vn.contentLanguage)): string {
  const escapeHtml = (value: string) => value.replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]!));
  // Reuse P02's inline raster policy. Package paths are accepted only in ZIP mode;
  // all other resources must be supported Data URIs. No downloads are performed.
  const inlineOrEmpty = (url: string) => isPackage && /^\.\/assets\/images\/(?:characters\/|backgrounds\/)?[a-z0-9_]+\.(?:png|jpg|gif|webp)$/.test(url) ? '' : url;
  prepareWebPackageAssets({ ...vn, coverUrl: inlineOrEmpty(vn.coverUrl),
    characters: vn.characters.map(c => ({ ...c, expressions: c.expressions.map(e => ({ ...e, imageUrl: inlineOrEmpty(e.imageUrl) })) })),
    scenes: vn.scenes.map(s => ({ ...s, backgroundUrl: inlineOrEmpty(s.backgroundUrl) })),
  });
  const vnData = JSON.stringify(vn).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');

  return `
<!DOCTYPE html>
<html lang="${escapeHtml(uiLanguage)}">
<head>
    <meta charset="UTF-8">
    <meta name="viewport" content="width=device-width, initial-scale=1.0">
    <title>${escapeHtml(vn.title)}</title>
    <style>
        body { font-family: system-ui, -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif; background-color: black; color: white; overflow: hidden; margin: 0; }
        * { box-sizing: border-box; }
        button { font: inherit; }
        #title-screen, #game-ui { position: fixed; inset: 0; }
        #title-screen { display: flex; align-items: center; justify-content: center; z-index: 50; background: #000; }
        #title-bg, #background, #characters-container { position: absolute; inset: 0; }
        #title-bg, #background { background-size: cover; background-position: center; }
        #title-bg { filter: brightness(.4) blur(2px); }
        #title-screen > div:last-child { position: relative; z-index: 1; text-align: center; padding: 2rem; max-width: 80rem; }
        #title-screen h1 { font-size: clamp(2rem, 7vw, 6rem); margin: 0 0 1rem; font-weight: 900; }
        #title-screen p { font-size: clamp(1rem, 2vw, 1.5rem); margin: 0 0 2rem; }
        #start-button { color: #0E1013; background: #C8F135; padding: 1rem 2rem; border: 0; border-radius: 2rem; cursor: pointer; font-size: 1.5rem; font-weight: 800; }
        #game-ui { overflow: hidden; background: #000; }
        #characters-container { display: flex; align-items: end; justify-content: center; pointer-events: none; }
        .player-panel { position: absolute; bottom: 2rem; left: 0; right: 0; margin: 0 auto; width: min(92%, 80rem); z-index: 30; }
        #ui-box { position: relative; padding: clamp(1rem, 3vw, 2.5rem); border-radius: 2rem; min-height: 9rem; }
        #dialogue-text { font-size: clamp(1rem, 2vw, 1.5rem); line-height: 1.7; max-height: 40vh; overflow-y: auto; }
        #choices-container { display: grid; gap: .75rem; margin-top: 1.5rem; max-height: 35vh; overflow-y: auto; }
        #player-status { position: fixed; top: 0; left: 0; right: 0; margin: 0; padding: .75rem; background: #441b1b; z-index: 100; }
        .choice-btn:focus-visible, #start-button:focus-visible { outline: 3px solid white; outline-offset: 3px; }
        .character-sprite {
            position: absolute;
            bottom: 0;
            height: 90%;
            transition: all 0.7s cubic-bezier(0.16, 1, 0.3, 1);
            max-width: none;
            object-fit: contain;
            filter: drop-shadow(0 20px 50px rgba(0,0,0,0.9));
        }
        .dialogue-box {
            background-color: rgba(10, 10, 10, 0.85);
            backdrop-filter: blur(20px);
            border: 1px solid rgba(255, 255, 255, 0.1);
            box-shadow: 0 -20px 50px rgba(0,0,0,0.5);
        }
        .choice-btn {
            width: 100%;
            text-align: center;
            padding: 1.25rem 2rem;
            background-color: rgba(200, 241, 53, 0.10);
            border: 1px solid rgba(200, 241, 53, 0.45);
            border-radius: 1.25rem;
            transition: all 0.4s;
            cursor: pointer;
            font-weight: 700;
            color: white;
            font-size: 1.125rem;
            position: relative;
            overflow: hidden;
        }
        .choice-btn:hover { background-color: rgba(200, 241, 53, 0.9); color: #0E1013; transform: translateY(-3px) scale(1.01); box-shadow: 0 10px 30px rgba(0,0,0,0.3); }
        .hidden { display: none !important; }
        @keyframes slideUp { from { transform: translateY(40px); opacity: 0; } to { transform: translateY(0); opacity: 1; } }
        .animate-slide-up { animation: slideUp 0.8s ease-out forwards; }
        @keyframes fadeIn { from { opacity: 0; } to { opacity: 1; } }
        .animate-fade-in { animation: fadeIn 1s ease-out forwards; }
        .name-tag {
            position: absolute;
            top: -2.5rem;
            left: 50%;
            transform: translateX(-50%);
            background: #C8F135;
            color: #0E1013;
            padding: 0.5rem 2.5rem;
            border-radius: 1rem 1rem 0 0;
            font-weight: 900;
            font-style: italic;
            font-size: 1.25rem;
            box-shadow: 0 -5px 20px rgba(200, 241, 53, 0.25);
            white-space: nowrap;
        }
        .text-wrap {
            white-space: pre-wrap;
            text-align: center;
        }
        /* 제목 잘림 방지 스타일 최적화: inline-block 및 충분한 padding-right 확보 */
        .title-text {
            line-height: 1.25;
            padding-bottom: 3.5rem;
            padding-left: 3rem;
            padding-right: 8rem;
            overflow: visible;
            display: inline-block;
        }
    </style>
</head>
<body onclick="handleScreenClick()">
    <p id="player-status" role="status" class="hidden"></p>
    <div id="title-screen" class="absolute inset-0 z-50 flex flex-col items-center justify-center bg-black">
        <div id="title-bg" class="absolute inset-0 bg-cover bg-center transition-transform duration-[10000ms]" style="filter: brightness(0.4) blur(2px);"></div>
        <div class="z-10 text-center p-8 animate-fade-in max-w-7xl overflow-visible">
            <h1 class="text-6xl md:text-9xl font-black text-white mb-8 drop-shadow-[0_20px_40px_rgba(0,0,0,0.9)] italic tracking-tighter text-wrap title-text">
                <span style="background: linear-gradient(to bottom, white, #9ca3af); -webkit-background-clip: text; -webkit-text-fill-color: transparent; padding-right: 2rem;">${escapeHtml(vn.title)}&nbsp;</span>
            </h1>
            <p class="text-xl md:text-2xl text-indigo-100/70 mb-16 max-w-3xl mx-auto italic leading-relaxed text-wrap">"${escapeHtml(vn.description)}"</p>
            <button id="start-button" onclick="event.stopPropagation(); startGame()" class="group relative px-16 py-6 bg-indigo-600 rounded-full text-3xl font-black hover:scale-110 transition-all shadow-[0_0_50px_rgba(79,70,229,0.5)] active:scale-95">${translate(uiLanguage, 'START JOURNEY')}</button>
        </div>
    </div>

    <div id="game-ui" class="absolute inset-0 hidden overflow-hidden">
        <div id="background" class="absolute inset-0 bg-cover bg-center transition-all duration-1000 scale-105"></div>
        <div id="characters-container" class="absolute inset-0 flex items-end justify-center pointer-events-none"></div>
        <div class="player-panel absolute bottom-10 left-1/2 -translate-x-1/2 w-[92%] max-w-6xl z-20 animate-slide-up">
            <div id="ui-box" class="relative p-10 rounded-[2.5rem] dialogue-box min-h-[14rem]">
                <div id="speaker-name" class="name-tag hidden"></div>
                <div id="dialogue-text" class="text-xl md:text-2xl leading-[1.7] font-medium drop-shadow-sm text-wrap"></div>
                <div id="choices-container" class="mt-10 grid grid-cols-1 md:grid-cols-2 gap-5 hidden"></div>
            </div>
        </div>
    </div>

    <script>
        const vn = ${vnData};
        let currentSceneId = vn.startSceneId;
        let dialogueIndex = 0;
        let isTyping = false;
        let currentTimer = null;
        let playing = false;

        function setBackground(element, url) {
            // Assign through the DOM, never interpolate an image into HTML/CSS markup.
            element.style.backgroundImage = url ? 'url(' + JSON.stringify(url) + ')' : 'none';
        }
        const initialScene = vn.scenes.find(s => s.id === vn.startSceneId);
        setBackground(document.getElementById('title-bg'), vn.coverUrl || (initialScene && initialScene.backgroundUrl) || '');

        function clearTyping() {
            if (currentTimer !== null) clearInterval(currentTimer);
            currentTimer = null;
            isTyping = false;
        }
        function startGame() {
            clearTyping();
            currentSceneId = vn.startSceneId;
            dialogueIndex = 0;
            playing = true;
            document.getElementById('player-status').classList.add('hidden');
            document.getElementById('title-screen').classList.add('hidden');
            document.getElementById('game-ui').classList.remove('hidden');
            document.getElementById('title-bg').style.transform = 'scale(1.2)';
            render();
        }
        function returnToTitle() {
            clearTyping();
            playing = false;
            currentSceneId = vn.startSceneId;
            dialogueIndex = 0;
            document.getElementById('game-ui').classList.add('hidden');
            document.getElementById('title-screen').classList.remove('hidden');
            document.getElementById('title-bg').style.transform = '';
        }
        function render() {
            clearTyping();
            const scene = vn.scenes.find(s => s.id === currentSceneId);
            const charContainer = document.getElementById('characters-container');
            const choicesEl = document.getElementById('choices-container');
            charContainer.replaceChildren();
            choicesEl.replaceChildren();
            choicesEl.classList.add('hidden');
            document.getElementById('speaker-name').classList.add('hidden');
            if (!scene) {
                setBackground(document.getElementById('background'), '');
                document.getElementById('dialogue-text').textContent = '';
                const status = document.getElementById('player-status');
                status.textContent = 'Missing scene: ' + currentSceneId;
                status.classList.remove('hidden');
                return;
            }
            const line = scene.dialogue[dialogueIndex] || { characterId: null, expressionId: null, text: '' };
            const isLast = dialogueIndex >= scene.dialogue.length - 1;
            setBackground(document.getElementById('background'), scene.backgroundUrl);
            scene.presentCharacterIds.forEach((id, idx) => {
                const char = vn.characters.find(c => c.id === id);
                if (!char) return;
                const expr = (line.characterId === id && line.expressionId && char.expressions.find(e => e.id === line.expressionId))
                    || char.expressions.find(e => e.name === '중립') || char.expressions[0];
                if (!expr || !expr.imageUrl) return;
                const img = document.createElement('img');
                img.src = expr.imageUrl;
                img.alt = char.name;
                img.onerror = () => img.remove();
                img.className = 'character-sprite';
                const total = scene.presentCharacterIds.length;
                img.style.left = total <= 1 ? '50%' : ((idx / (total - 1)) * 50 + 25) + '%';
                img.style.transform = line.characterId === id ? 'translateX(-50%) scale(1.05)' : 'translateX(-50%) scale(.95)';
                img.style.filter = line.characterId === id ? 'brightness(1)' : 'brightness(.4) grayscale(.2)';
                img.style.zIndex = line.characterId === id ? '20' : '10';
                charContainer.appendChild(img);
            });
            const speaker = vn.characters.find(c => c.id === line.characterId);
            const nameEl = document.getElementById('speaker-name');
            if (speaker) { nameEl.textContent = speaker.name; nameEl.classList.remove('hidden'); }
            typeText(line.text);
            if (isLast && scene.choices.length > 0) {
                choicesEl.classList.remove('hidden');
                scene.choices.forEach(choice => {
                    const button = document.createElement('button');
                    button.type = 'button';
                    button.className = 'choice-btn';
                    button.textContent = choice.text;
                    button.onclick = event => {
                        event.stopPropagation();
                        currentSceneId = choice.nextSceneId;
                        dialogueIndex = 0;
                        render();
                    };
                    choicesEl.appendChild(button);
                });
            }
        }
        function typeText(text) {
            clearTyping();
            const element = document.getElementById('dialogue-text');
            element.textContent = '';
            if (!text) return;
            isTyping = true;
            let index = 0;
            currentTimer = setInterval(() => {
                element.textContent += text[index++];
                if (index >= text.length) clearTyping();
            }, 30);
        }
        function handleScreenClick() {
            if (!playing) return;
            const scene = vn.scenes.find(s => s.id === currentSceneId);
            if (!scene) { returnToTitle(); return; }
            if (isTyping) {
                clearTyping();
                document.getElementById('dialogue-text').textContent = (scene.dialogue[dialogueIndex] || { text: '' }).text;
                return;
            }
            if (dialogueIndex < scene.dialogue.length - 1) { dialogueIndex++; render(); }
            else if (scene.choices.length === 0) returnToTitle();
        }
    </script>
</body>
</html>`;
}
